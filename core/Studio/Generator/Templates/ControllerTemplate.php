<?php

declare(strict_types=1);

namespace CWF\Studio\Generator;

/**
 * Controller Template Generator
 */
class ControllerTemplate
{
    public function generate(array $config): string
    {
        $name = $config['name'];
        $namespace = $config['namespace'];
        $methods = $config['methods'];
        $useAI = $config['use_ai'] ?? false;

        $code = "<?php\n\n";
        $code .= "declare(strict_types=1);\n\n";
        $code .= "namespace {$namespace};\n\n";
        $code .= "use CWF\\Http\\Request;\n";
        $code .= "use CWF\\Http\\Response;\n";

        if ($useAI) {
            $code .= "use CWF\\AI\\AIManager;\n";
        }

        $code .= "\n/**\n";
        $code .= " * {$name}\n";
        $code .= " *\n";
        $code .= " * Auto-generated by CWFramework Studio\n";
        $code .= " * @generated " . date('Y-m-d H:i:s') . "\n";
        $code .= " */\n";
        $code .= "class {$name}\n";
        $code .= "{\n";

        if ($useAI) {
            $code .= "    public function __construct(\n";
            $code .= "        private readonly AIManager \$ai\n";
            $code .= "    ) {}\n\n";
        }

        foreach ($methods as $method) {
            $code .= $this->generateMethod($method, $useAI);
        }

        $code .= "}\n";

        return $code;
    }

    private function generateMethod(string $method, bool $useAI): string
    {
        $code = "    /**\n";
        $code .= "     * {$method} method\n";
        $code .= "     */\n";
        $code .= "    public function {$method}(Request \$request): Response\n";
        $code .= "    {\n";

        switch ($method) {
            case 'index':
                $code .= "        // List all items\n";
                $code .= "        \$items = db('table_name')->get();\n";
                $code .= "        return json(\$items);\n";
                break;

            case 'show':
                $code .= "        // Show single item\n";
                $code .= "        \$id = \$request->input('id');\n";
                $code .= "        \$item = db('table_name')->find(\$id);\n";
                $code .= "        return json(\$item);\n";
                break;

            case 'store':
                $code .= "        // Create new item\n";
                $code .= "        \$data = \$request->all();\n";
                $code .= "        \$id = db('table_name')->insert(\$data);\n";
                $code .= "        return json(['id' => \$id], 201);\n";
                break;

            case 'update':
                $code .= "        // Update item\n";
                $code .= "        \$id = \$request->input('id');\n";
                $code .= "        \$data = \$request->all();\n";
                $code .= "        db('table_name')->where('id', \$id)->update(\$data);\n";
                $code .= "        return json(['success' => true]);\n";
                break;

            case 'destroy':
                $code .= "        // Delete item\n";
                $code .= "        \$id = \$request->input('id');\n";
                $code .= "        db('table_name')->where('id', \$id)->delete();\n";
                $code .= "        return json(['success' => true]);\n";
                break;

            default:
                if ($useAI) {
                    $code .= "        // AI-powered method\n";
                    $code .= "        \$response = \$this->ai->chat([\n";
                    $code .= "            ['role' => 'user', 'content' => 'Process request']\n";
                    $code .= "        ]);\n";
                    $code .= "        return json(['ai_response' => \$response->getContent()]);\n";
                } else {
                    $code .= "        // TODO: Implement {$method} logic\n";
                    $code .= "        return json(['message' => '{$method} method']);\n";
                }
        }

        $code .= "    }\n\n";

        return $code;
    }
}
