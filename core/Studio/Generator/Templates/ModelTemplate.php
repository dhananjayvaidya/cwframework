<?php

declare(strict_types=1);

namespace CWF\Studio\Generator;

/**
 * Model Template Generator
 */
class ModelTemplate
{
    public function generate(array $config): string
    {
        $name = $config['name'];
        $table = $config['table'];
        $fields = $config['fields'];

        $code = "<?php\n\n";
        $code .= "declare(strict_types=1);\n\n";
        $code .= "namespace App\\Models;\n\n";
        $code .= "/**\n";
        $code .= " * {$name} Model\n";
        $code .= " *\n";
        $code .= " * Auto-generated by CWFramework Studio\n";
        $code .= " * @generated " . date('Y-m-d H:i:s') . "\n";
        $code .= " */\n";
        $code .= "class {$name}\n";
        $code .= "{\n";
        $code .= "    protected string \$table = '{$table}';\n\n";

        // Generate field properties
        foreach ($fields as $field => $type) {
            $phpType = $this->mapFieldType($type);
            $code .= "    public {$phpType} \${$field};\n";
        }

        $code .= "\n";

        // Generate methods
        $code .= $this->generateAllMethod();
        $code .= $this->generateFindMethod();
        $code .= $this->generateCreateMethod();
        $code .= $this->generateUpdateMethod();
        $code .= $this->generateDeleteMethod();

        $code .= "}\n";

        return $code;
    }

    private function mapFieldType(string $type): string
    {
        return match(strtolower($type)) {
            'int', 'integer', 'bigint' => 'int',
            'float', 'double', 'decimal' => 'float',
            'bool', 'boolean' => 'bool',
            'array', 'json' => 'array',
            default => 'string'
        };
    }

    private function generateAllMethod(): string
    {
        return <<<'PHP'
    /**
     * Get all records
     */
    public function all(): array
    {
        return db($this->table)->get();
    }


PHP;
    }

    private function generateFindMethod(): string
    {
        return <<<'PHP'
    /**
     * Find record by ID
     */
    public function find(int $id): ?array
    {
        return db($this->table)->find($id);
    }


PHP;
    }

    private function generateCreateMethod(): string
    {
        return <<<'PHP'
    /**
     * Create new record
     */
    public function create(array $data): int
    {
        return db($this->table)->insert($data);
    }


PHP;
    }

    private function generateUpdateMethod(): string
    {
        return <<<'PHP'
    /**
     * Update record
     */
    public function update(int $id, array $data): int
    {
        return db($this->table)->where('id', $id)->update($data);
    }


PHP;
    }

    private function generateDeleteMethod(): string
    {
        return <<<'PHP'
    /**
     * Delete record
     */
    public function delete(int $id): int
    {
        return db($this->table)->where('id', $id)->delete();
    }

PHP;
    }
}

class MiddlewareTemplate
{
    public function generate(array $config): string
    {
        $name = $config['name'];
        $logic = $config['logic'] ?? '';

        return <<<PHP
<?php

declare(strict_types=1);

namespace App\\Middleware;

use CWF\\Http\\Request;
use CWF\\Http\\Response;
use Closure;

/**
 * {$name}
 *
 * Auto-generated by CWFramework Studio
 * @generated {date('Y-m-d H:i:s')}
 */
class {$name}
{
    public function handle(Request \$request, Closure \$next): Response
    {
        // Before request
        {$logic}

        \$response = \$next(\$request);

        // After request

        return \$response;
    }
}
PHP;
    }
}

